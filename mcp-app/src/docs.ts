// Generates the README tool reference from the registry. Run with `npm run docs`; the tests fail if it is stale.
import type { AnySpec } from "./registry.js";

export const START = "<!-- tool-reference:start (generated by `npm run docs`; edit src/tools.ts instead) -->";
export const END = "<!-- tool-reference:end -->";

const widgetText = { none: "never", on_request: "only when asked", review: "Submit review" } as const;
const cell = (s: string) => s.replace(/\|/g, "\\|");

export function renderToolReference(specs: AnySpec[]): string {
  const model = specs.filter((s) => s.access === "model");
  const app = specs.filter((s) => s.access === "app");
  const rows = (list: AnySpec[]) =>
    list.map((s) => `| \`${s.name}\` | ${s.group} | ${s.annotations.readOnlyHint ? "read-only" : s.annotations.destructiveHint ? "destructive" : "writes"} | ${widgetText[s.widget]} | ${cell(s.whenToUse)} | ${cell(s.whenNotToUse)} | ${cell(s.next)} |`).join("\n");
  return [
    `${model.length} tools for the model, ${app.length} app-only buttons (generated from \`src/tools.ts\`).`,
    "",
    "| Tool | Group | Effect | Opens a view | Use when | Not for | Next |",
    "|---|---|---|---|---|---|---|",
    rows(model),
    "",
    "App-only buttons (hidden from the model; only a rendered view may call them):",
    "",
    "| Tool | Group | Effect | Opens a view | Use when | Not for | Next |",
    "|---|---|---|---|---|---|---|",
    rows(app),
  ].join("\n");
}

export function updateReadme(readme: string, specs: AnySpec[]): string {
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a < 0 || b < a) throw new Error("README.md is missing the tool-reference markers");
  return `${readme.slice(0, a)}${START}\n${renderToolReference(specs)}\n${readme.slice(b)}`;
}
