// Builds the guidance bundle (src/generated/guidance-bundle.ts) from the editable files in guidance/.
// Plain JS so it runs before any TypeScript can be loaded; used by `npm run docs` and compared by the tests.
import { readdirSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(ROOT, "guidance", p), "utf8").replace(/\n+$/, "");

export function buildBundle() {
  const topics = {};
  for (const f of readdirSync(join(ROOT, "guidance", "topics")).filter((x) => x.endsWith(".md")).sort()) topics[f.slice(0, -3)] = read(`topics/${f}`);
  const bundle = {
    instructions: read("instructions.md"),
    widgetRules: { on_request: read("widgets-on-request.md"), off: read("widgets-off.md") },
    topics,
    skills: JSON.parse(read("skills.json")),
  };
  return `// Generated by \`npm run docs\` from guidance/. Do not edit; edit guidance/ and run the command again.\nexport const GUIDANCE = ${JSON.stringify(bundle, null, 2)} as const;\n`;
}
export const BUNDLE_PATH = join(ROOT, "src", "generated", "guidance-bundle.ts");
